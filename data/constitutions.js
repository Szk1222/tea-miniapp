function rebuildMap() {
  Object.keys(MAP).forEach(function (k) { delete MAP[k]; });
  CONSTITUTIONS.forEach(function (c) { MAP[c.id] = c; });
}
function rebuildIds() {
  IDS.length = 0;
  CONSTITUTIONS.forEach(function (c) { IDS.push(c.id); });
}
